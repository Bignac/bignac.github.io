const { chromium } = require('playwright-core')
const path = require('path')
;(async () => {
  const b = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, args: ['--autoplay-policy=no-user-gesture-required'] })
  const p = await b.newPage({ viewport: { width: 1440, height: 900 } })
  const t0 = Date.now()
  await p.goto('http://127.0.0.1:5173', { waitUntil: 'networkidle' })
  await p.setInputFiles('input[type=file]', path.join(__dirname, 'fixtures/sample-person.webm'))
  await p.waitForSelector('.asset-tile', { timeout: 20000 })
  await p.waitForTimeout(500)
  await p.locator('.canvas-quick-cutout').click()
  await p.waitForTimeout(9000)
  await p.locator('.artboard').screenshot({ path: '/tmp/probe-cutout.png' })
  const status = await p.locator('.canvas-status').textContent()
  console.log('STATUS', status, 'elapsed', Date.now() - t0)
  await b.close()
})()
